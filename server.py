def resolve_place_by_fuzzy_name(q):
    if not q:
        return None
    ql = str(q).strip().lower()
    if not ql or ql in ("null", "none", "невідомо", "неизвестно"):
        return None
    if q in PLACE_BY_NAME:
        return PLACE_BY_NAME[q]
    for n, la, lo, rx in PLACES:
        if n.lower() == ql or n.replace(" (ЗП)", "").lower() == ql:
            return (n, la, lo)
    for n, la, lo, rx in PLACES:
        if re.search(rx, ql, re.I):
            return (n, la, lo)
    return None

