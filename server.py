def feed_add(ts, ch, text, kinds, pos, tgt):
    key = (ch, text[:65])
    if key in fed:
        return
    fed.add(key)
    place_str = " -> ".join(p[0] for p in (pos, tgt) if p)
    feed.insert(0, dict(t=ts, ch=ch, text=text[:220], kinds=kinds or ["drone"], place=place_str))
    del feed[50:]

def resolve_tracks_status(kinds, loc, status_label, one=True):
    now = time.time()
    cand = [
        t for t in tracks.values()
        if not t.get("ended")
        and (not kinds or t["kind"] in kinds)
        and (
            not loc
            or hav(t["lat"], t["lon"], loc[1], loc[2]) < 30
            or (t["goal"] and hav(t["goal"][1], t["goal"][2], loc[1], loc[2]) < 20)
        )
    ]
    if not cand and not loc:
        cand = [t for t in tracks.values() if not t.get("ended") and (not kinds or t["kind"] in kinds)]

    if one and cand:
        if loc:
            cand = [min(cand, key=lambda t: hav(t["lat"], t["lon"], loc[1], loc[2]))]
        else:
            cand = [max(cand, key=lambda t: t["seen"])]

    for t in cand:
        t["ended"] = True
        t["auto_ended"] = False
        t["ended_at"] = now
        t["v"] = 0
        t["status_msg"] = status_label
        t["seen"] = now

def infer_implicit_subs(tl, pos, tgt, ch):
    m_cnt = ANY_CNT_RX.search(tl)
    cnt = m_cnt.group(1) if m_cnt else None
    if IMPLICIT_KAB_RX.search(tl):
        return [(SUB["kab"], cnt)]
    now = time.time()
    live_drones = [t for t in tracks.values() if t["kind"] == "drone" and not t.get("ended") and now - t["seen"] < t["ttl"]]
    if live_drones:
        ref = pos or tgt
        if ref:
            near = min(live_drones, key=lambda t: hav(t["lat"], t["lon"], ref[1], ref[2]))
            return [(SUB[near["sub"]], cnt)]
        latest = max(live_drones, key=lambda t: t["seen"])
        return [(SUB[latest["sub"]], cnt)]
    if pos or tgt or IMPLICIT_FLIGHT_RX.search(tl):
        return [(SUB["geran2"], cnt)]
    return []

def act(intent, subs, pos, tgt, ts, text, ch, how="", v_ovr=None, hdg_ovr=None, from_brg=None, is_turn=False, is_loiter=False, force_new=False, msg_key=None):
    loc = pos or tgt
    kinds = list(dict.fromkeys(sb["kind"] for sb, _ in subs if sb["kind"] not in ("strike", "impact")))
    tag = f"{ch}{how}: «{text[:55]}» -> "

    if intent == "downed":
        resolve_tracks_status(kinds, loc, "ЗБИТО", one=True)
        feed_add(ts, ch, text, kinds or ["drone"], pos, tgt)
        return note(tag + "ЗБИТО")

    if intent == "clear":
        resolve_tracks_status(kinds, loc, "ВІДБІЙ / ЧИСТО", one=False)
        feed_add(ts, ch, text, kinds or ["drone"], pos, tgt)
        return note(tag + "ВІДБІЙ / ЧИСТО")

    if intent == "impact":
        if loc and loc[0] not in BROAD_REGIONS:
            m = upsert(SUB["impact"], loc, None, ts, text, ch=ch, cnt=next((c for _, c in subs if c), None))
            if m:
                m["label"] = "ПРИЛІТ"
        feed_add(ts, ch, text, ["impact"] + kinds, pos, tgt)
        return note(tag + f"ПРИЛІТ ({loc and loc[0] or ''})")

    if not subs:
        subs = infer_implicit_subs(text.lower(), pos, tgt, ch)
        if not subs:
            return note(tag + "немає типу цілі, пропуск")

    now = time.time()
    has_live_drone = any(not t.get("ended") and t["kind"] == "drone" and now - t["seen"] < t["ttl"] for t in tracks.values())
    is_drone_sub = any(sb["kind"] == "drone" for sb, _ in subs)
    if is_drone_sub and pos and not tgt and has_live_drone and not VIA_PRE_RX.search(text.lower()) and not is_loiter and not force_new and pos[0] not in LAUNCH_ONLY_ORIGINS:
        if is_turn or TO_PRE_RX.search(text.lower()) or not detect(text.lower()) or pos[0] in ZP_DISTRICTS:
            tgt, pos = pos, None
            is_turn = True

    for sb, cnt in subs:
        ch_last_sub[ch] = (time.time(), sb)
        if sb["kind"] == "strike":
            if loc and loc[0] not in BROAD_REGIONS:
                upsert(sb, loc, None, ts, text, ch=ch, cnt=cnt, msg_key=msg_key)
        else:
            upsert(sb, pos, tgt, ts, text, ch=ch, cnt=cnt, v_ovr=v_ovr, hdg_ovr=hdg_ovr, from_brg=from_brg, is_turn=is_turn, is_loiter=is_loiter, force_new=force_new, msg_key=msg_key)
    feed_add(ts, ch, text, [sb["kind"] for sb, _ in subs], pos, tgt)
    note(tag + f"{[(sb['id'], c) for sb, c in subs]} поз={pos and pos[0]} ціль={tgt and tgt[0]} курс={hdg_ovr}")

def split_clauses_by_target_types(seg):
    parts = re.split(
        r"(?:[.;!?\n]+|\s+[—–]\s+(?=(?:бпла|шах|каб|ракет|реакт|пуск|молн|фпв|fpv|ланцет|гербер|орлан|розвід))|,\s*(?=(?:а\s+також\s+|також\s+|тим\s+часом\s+)?(?:бпла|шах\w*|геран\w*|мопед\w*|реакт\w*|молні\w*|молни\w*|фпв\w*|fpv|ланцет\w*|гербер\w*|орлан\w*|розвід\w*|каб\w*|фаб\w*|пуск\w*|ракет\w*|баліст\w*)))",
        seg,
        flags=re.I
    )
    return [p.strip() for p in parts if len(p.strip()) >= 2]

def ingest_segment(ts, seg, ch="", msg_key=None, inherited_subs=None, reply_ctx=None, full_post_has_zp=False):
    tl = seg.lower()
    routes = extract_routes(tl)
    has_zp = bool(ZP_UNIQUE_RX.search(tl)) or bool(routes) or full_post_has_zp or bool(reply_ctx and ZP_UNIQUE_RX.search(reply_ctx.get("text", "").lower()))

    if OTHER_OBLAST_RX.search(tl) and not ZP_UNIQUE_RX.search(tl) and not routes:
        return []

    if ch.lower() in ALL_UA_CHANNELS and not has_zp:
        return []

    if PURE_ALARM_RX.match(tl):
        feed_add(ts, ch, seg, ["kab"], None, None)
        return []

    intent = intent_of(tl)
    subs = detect(tl)
    if not subs:
        if inherited_subs and all(sb["kind"] == "drone" for sb, _ in inherited_subs) and not IMPLICIT_KAB_RX.search(tl):
            subs = inherited_subs
        elif reply_ctx and reply_ctx.get("subs"):
            subs = reply_ctx.get("subs")
        else:
            subs = []

    v_ovr, hdg_ovr = parse_speed_hdg(tl)
    from_brg = parse_approach_from_bearing(tl)
    is_turn = bool(TURN_RX.search(tl))
    is_loiter = bool(LOITER_RX.search(tl))
    force_new = bool(NEW_TARGET_WORDS_RX.search(tl))

    if not ZP_UNIQUE_RX.search(tl) and ch.lower() in ALL_UA_CHANNELS and routes:
        routes = [
            (p, g) for (p, g) in routes
            if not ((p and p[0] in AMBIGUOUS_PLACES) or (g and g[0] in AMBIGUOUS_PLACES))
        ]

    if not routes and reply_ctx and reply_ctx.get("routes"):
        if intent in ("clear", "downed", "impact"):
            r0 = reply_ctx["routes"][0]
            loc = r0[1] or r0[0]
            routes = [(loc, None)] if loc else []
        elif is_turn or hdg_ovr is not None:
            r0 = reply_ctx["routes"][0]
            routes = [(r0[1] or r0[0], None)]

    if intent in ("clear", "downed", "impact") and not routes:
        if has_zp or ch.lower() not in ALL_UA_CHANNELS:
            act(intent, subs, None, None, ts, seg, ch, msg_key=msg_key)
        return subs

    if not routes and subs and (has_zp or ch.lower() not in ALL_UA_CHANNELS):
        live_drones = [t for t in tracks.values() if t["kind"] == "drone" and not t.get("ended")]
        if (hdg_ovr is not None or is_loiter) and live_drones and not force_new:
            latest = max(live_drones, key=lambda c: c["seen"])
            if is_loiter:
                latest["loiter"] = True
                latest["status_msg"] = f"Кружляє ({latest['frm']})"
                latest["seen"] = time.time()
                return subs
            if hdg_ovr is not None:
                latest["loiter"] = False
                proj_km = 18.0 if latest["v"] < 400 else 45.0
                gla, glo = fwd(latest["lat"], latest["lon"], hdg_ovr, proj_km)
                latest["goal"] = (f"курс {round(hdg_ovr)}°", gla, glo)
                latest["to_name"] = f"курс {round(hdg_ovr)}°"
                latest["passed_goal"] = False
                latest["thdg"] = hdg_ovr
                latest["status_msg"] = None
                latest["seen"] = time.time()
                return subs
        routes = [default_route_for_sub(subs[0][0], from_brg=from_brg, hdg_ovr=hdg_ovr)]

    if not routes:
        if hdg_ovr is not None and tracks and (has_zp or ch.lower() not in ALL_UA_CHANNELS):
            live = [t for t in tracks.values() if t["kind"] == "drone" and not t.get("ended")]
            if live:
                latest = max(live, key=lambda c: c["seen"])
                latest["loiter"] = False
                proj_km = 18.0 if latest["v"] < 400 else 45.0
                gla, glo = fwd(latest["lat"], latest["lon"], hdg_ovr, proj_km)
                latest["goal"] = (f"курс {round(hdg_ovr)}°", gla, glo)
                latest["to_name"] = f"курс {round(hdg_ovr)}°"
                latest["passed_goal"] = False
                latest["thdg"] = hdg_ovr
                latest["status_msg"] = None
                latest["seen"] = time.time()
                return subs
        elif is_loiter and tracks:
            live = [t for t in tracks.values() if t["kind"] == "drone" and not t.get("ended")]
            if live:
                latest = max(live, key=lambda c: c["seen"])
                latest["loiter"] = True
                latest["status_msg"] = f"Кружляє ({latest['frm']})"
                latest["seen"] = time.time()
                return subs
        return subs

    if intent == "impact" and not [1 for sb, _ in subs if sb["kind"] != "strike"]:
        subs = [x for x in subs if x[0]["id"] != "arty"]

    for r_idx, (pos, tgt) in enumerate(routes):
        r_key = f"{msg_key}:r{r_idx}" if msg_key else None
        act(intent, subs, pos, tgt, ts, seg, ch, v_ovr=v_ovr, hdg_ovr=hdg_ovr, from_brg=from_brg, is_turn=is_turn, is_loiter=is_loiter, force_new=force_new, msg_key=r_key)
    return subs

def ingest(ts, text, ch="", msg_key=None, reply_ctx=None):
    now = time.time()
    for t in tracks.values():
        step(t, now)
    cleaned = clean_post(text)
    if not cleaned or REAL_NEWS_RX.search(cleaned.lower()) or len(cleaned) > 650:
        return note(f"{ch}: «{text[:50]}» -> новина/не зведення, пропуск")
    full_has_zp = bool(ZP_UNIQUE_RX.search(cleaned.lower()))
    clauses = []
    for ln in cleaned.split("\n"):
        ln_s = ln.strip(" •▪▫-*—–")
        if len(ln_s) >= 2:
            clauses.extend(split_clauses_by_target_types(ln_s))

    if len(clauses) > 1:
        inherited = []
        for idx, cl in enumerate(clauses):
            sub_key = f"{msg_key}:{idx}" if msg_key else None
            cur_subs = ingest_segment(ts, cl, ch, msg_key=sub_key, inherited_subs=inherited, reply_ctx=reply_ctx, full_post_has_zp=full_has_zp)
            if cur_subs and all(sb["kind"] == "drone" for sb, _ in cur_subs):
                inherited = cur_subs
    elif clauses:
        ingest_segment(ts, clauses[0], ch, msg_key=msg_key, reply_ctx=reply_ctx, full_post_has_zp=full_has_zp)

async def process(s, ts, text, ch, msg_key=None, reply_ctx=None):
    try:
        cleaned = clean_post(text)
        if not cleaned or REAL_NEWS_RX.search(cleaned.lower()) or len(cleaned) > 650:
            return
        ingest(ts, cleaned, ch, msg_key=msg_key, reply_ctx=reply_ctx)
        await push()
    except Exception as e:
        print("process error:", e)

