async def llm_fallback_parse(session, text):
    """Якщо увімкнено зовнішній LLM ключ і нестандартний текст не розпізнано локальним гео-парсером,
    звертається до хмарного ШІ для виділення типу цілі, точки вильоту та вектора."""
    if not (GROQ_KEY or GEMINI_KEY or OPENAI_KEY):
        return None
    prompt = (
        "Ти тактичний ШІ-диспетчер радару Запоріжжя. Проаналізуй повідомлення і поверни JSON: "
        '{"kind":"drone|kab|missile|clear|downed|impact", "from":"назва н.п. або null", "to":"назва н.п./району ЗП або null", "hdg":null_or_deg}. '
        f"Повідомлення: {text}"
    )
    try:
        if GROQ_KEY:
            async with session.post(
                "https://api.groq.com/openai/v1/chat/completions",
                headers={"Authorization": f"Bearer {GROQ_KEY}", "Content-Type": "application/json"},
                json={"model": "llama-3.3-70b-versatile", "messages": [{"role": "user", "content": prompt}], "temperature": 0.0, "response_format": {"type": "json_object"}},
                timeout=aiohttp.ClientTimeout(total=3.0)
            ) as r:
                if r.status == 200:
                    d = await r.json()
                    return json.loads(d["choices"][0]["message"]["content"])
    except Exception:
        return None
    return None

def build_ai_summary(vis_tracks):
    """Формує розумне тактичне зведення ШІ в реальному часі на основі всіх векторів та загроз."""
    active = [t for t in vis_tracks if not t.get("ended") and t["kind"] not in ("strike", "impact")]
    if not active:
        return {
            "level": "green",
            "headline": "Повітряний простір Запоріжжя та області чистий",
            "details": "ШІ-моніторинг не фіксує активних БпЛА, КАБів чи ракетних цілей у секторі відповідальності.",
            "recommendations": []
        }
    kabs = [t for t in active if t["kind"] == "kab"]
    missiles = [t for t in active if t["kind"] == "missile"]
    drones = [t for t in active if t["kind"] == "drone"]

    recs = []
    for t in active[:4]:
        th = ", ".join(t.get("threats") or [])
        route = f"{t['frm']} → {t['to']}" if t.get("to") else f"район {t['frm']} (маневрує)"
        eta_tx = f", підліт ~{t['eta']} с" if t.get("eta") else ""
        recs.append(f"{t['name']}: {route}{eta_tx}" + (f" · у секторі: {th}" if th else ""))

    if missiles or kabs:
        urgent = (missiles + kabs)[0]
        return {
            "level": "red",
            "headline": f"КРИТИЧНА ЗАГРОЗА: {urgent['name']} ({urgent['frm']}{' → ' + urgent['to'] if urgent.get('to') else ''})",
            "details": f"Активних цілей: {len(active)} (КАБ/Ракети: {len(kabs)+len(missiles)}, БпЛА: {len(drones)}). ШІ прогнозує вектор руху в сектор: {', '.join(urgent.get('threats') or [urgent.get('to') or 'Запорізький р-н'])}.",
            "recommendations": recs
        }

    nearest = min(drones, key=lambda x: x["home"])
    in_city = [t for t in drones if t["home"] <= 8.5]
    if in_city:
        c0 = in_city[0]
        return {
            "level": "amber",
            "headline": f"УВАГА: {c0['name']} у повітряному просторі Запоріжжя ({c0['to'] or c0['frm']})",
            "details": f"Усього БпЛА: {len(drones)}. Найближча ціль за {c0['home']} км від центру. " + (f"Вектор загрози: {', '.join(c0['threats'])}." if c0.get("threats") else "Ціль маневрує, очікується уточнення курсу по мікрорайонах."),
            "recommendations": recs
        }

    return {
        "level": "amber",
        "headline": f"Моніторинг БпЛА ({len(drones)} ціл.) · найближча за {nearest['home']} км ({nearest['frm']}{' → ' + nearest['to'] if nearest.get('to') else ''})",
        "details": f"ШІ відстежує траєкторії підльоту. " + (f"Потенційні орієнтири за курсом: {', '.join(nearest['threats'])}." if nearest.get("threats") else "Прямої загрози центру міста в цю секунду немає."),
        "recommendations": recs
    }

async def process(s, ts, text, ch, msg_key=None, reply_ctx=None):
    try:
        cleaned = clean_post(text)
        if not cleaned or REAL_NEWS_RX.search(cleaned.lower()) or len(cleaned) > 650:
            return
        before_ok = ai_stats["ok"]
        ingest(ts, cleaned, ch, msg_key=msg_key, reply_ctx=reply_ctx)
        if ai_stats["ok"] == before_ok and (GROQ_KEY or GEMINI_KEY or OPENAI_KEY):
            llm_res = await llm_fallback_parse(s, cleaned)
            if llm_res and llm_res.get("to"):
                ingest(ts, f"БпЛА курс на {llm_res['to']}", ch, msg_key=msg_key)
        await push()
    except Exception as e:
        print("process error:", e)

