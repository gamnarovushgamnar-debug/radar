def sanitize_tactical_route(sub_kind, pos, tgt, hdg_ovr=None, manual=False):
    """Перевіряє фізичну реалістичність маршруту БЕЗ ВИГАДУВАННЯ КУРСУ:
    якщо КАБ заспавнено вручну або відомий тільки рубіж пуску без цілі — КАБ ЧЕКАЄ НА КУРС (tgt=None)."""
    if manual:
        return pos, tgt, hdg_ovr, (tgt is None and hdg_ovr is None)

    provisional = False
    if pos and pos[0] in BROAD_REGIONS:
        pos = None
    if tgt and tgt[0] in BROAD_REGIONS:
        tgt = None

    if sub_kind == "missile":
        if not pos and tgt:
            pos = ("південно-східний напрямок", 47.15, 36.80)
        return pos, tgt, hdg_ovr, (tgt is None and hdg_ovr is None)

    if sub_kind == "kab":
        if hdg_ovr is not None and (80.0 <= hdg_ovr <= 225.0):
            hdg_ovr = None
        if pos and not tgt:
            if hdg_ovr is not None:
                gla, glo = fwd(pos[1], pos[2], hdg_ovr, 26.0)
                tgt = (f"курс {round(hdg_ovr)}°", gla, glo)
                provisional = True
            else:
                # КАБ без вказаної цілі або курсу НІКОЛИ не летить сам куди попало — чекає на курс!
                provisional = True
        if not pos and tgt:
            pos = real_kab_launch_origin_for(tgt)
        if not pos and not tgt:
            pos = ("Токмак", 47.254, 35.704)
            if hdg_ovr is not None:
                gla, glo = fwd(pos[1], pos[2], hdg_ovr, 26.0)
                tgt = (f"курс {round(hdg_ovr)}°", gla, glo)
            provisional = True
        if pos and tgt:
            b = brg(pos[1], pos[2], tgt[1], tgt[2])
            if (75.0 <= b <= 230.0) or (is_free_territory(pos[1], pos[2]) and not (250.0 <= b <= 360.0 or 0.0 <= b <= 50.0)):
                pos = real_kab_launch_origin_for(tgt)
        return pos, tgt, hdg_ovr, provisional

    return pos, tgt, hdg_ovr, provisional

def default_lookahead_km(t):
    if t.get("sub") == "fpv":
        return 2.2
    if t.get("sub") in TACTICAL_SHORT_DRONES or t.get("sub") in ("recon", "orlan"):
        return 3.5
    if t.get("kind") == "kab":
        return 12.0
    if t.get("kind") == "missile":
        return 20.0
    return 5.5

def effective_speed(t):
    v = t["v"]
    if not v or t.get("ended") or t.get("holding") or t.get("loiter"):
        return 0
    if t["kind"] == "kab":
        flown = hav(*t["o"], t["lat"], t["lon"])
        factor = max(0.80, 1.0 - 0.20 * (flown / KAB_RANGE))
        return round(v * factor)
    return v

def step(t, now):
    dt = min(max(0.0, now - t["ls"]), 30.0)
    if dt <= 0:
        return
    t["ls"] = now
    if t.get("ended") or t.get("holding") or t.get("loiter"):
        return
    v_eff = effective_speed(t)
    if not v_eff or t.get("hdg") is None:
        return

    step_km = v_eff * dt / 3600.0
    g = t.get("goal")
    look_km = default_lookahead_km(t)

    if g:
        rem_g = hav(t["lat"], t["lon"], g[1], g[2])
        if rem_g > step_km and rem_g > 0.15:
            t["lat"], t["lon"] = fwd(t["lat"], t["lon"], t["hdg"], step_km)
        else:
            t["lat"], t["lon"] = g[1], g[2]
            if str(g[0]).startswith("курс"):
                gla, glo = fwd(t["lat"], t["lon"], t["hdg"], look_km)
                t["goal"] = (g[0], gla, glo)
            else:
                t["frm"] = g[0]
                t["status_msg"] = f"В районі {g[0]}"
                t["passed_goal"] = True
                t["passed_at"] = now
                t["holding"] = True
                t["goal"] = None
    else:
        t["holding"] = True

    if t["kind"] == "kab" and not t.get("holding") and hav(*t["o"], t["lat"], t["lon"]) >= KAB_RANGE:
        t["ended"] = True
        t["auto_ended"] = True
        t["status_msg"] = "Локаційно не фіксується"
        t["ended_at"] = now

    umax = 4.0 if v_eff < 400 else 7.0
    t["unc"] = min(umax, t["unc"] + dt * v_eff / 3600 * 0.03)

def can_fuse_into_track(c, sub, pos, tgt, hdg_ovr, te, is_turn=False, force_new=False):
    if force_new:
        return False, 999.0
    if c["kind"] != sub["kind"]:
        return False, 999.0
    if c.get("ended") and not c.get("auto_ended"):
        return False, 999.0

    if sub["kind"] == "kab":
        if (c.get("provisional_goal") or (c.get("holding") and not c.get("passed_goal"))) and (time.time() - c.get("seen", 0) <= 240):
            return True, 0.04
        if tgt and c.get("goal"):
            g_dist = hav(tgt[1], tgt[2], c["goal"][1], c["goal"][2])
            if g_dist <= 22.0:
                return True, g_dist / 25.0
        if tgt and c.get("holding"):
            d_cur = hav(tgt[1], tgt[2], c["lat"], c["lon"])
            if d_cur <= 95.0:
                return True, d_cur / 100.0
        if (is_turn or hdg_ovr is not None) and not pos and not tgt:
            return True, 0.15
        return False, 999.0

    if sub["kind"] == "missile":
        if c.get("holding") and not c.get("passed_goal"):
            return True, 0.05
        if tgt and c.get("goal") and hav(tgt[1], tgt[2], c["goal"][1], c["goal"][2]) <= 35.0:
            return True, 0.2
        return False, 999.0

    if not sub.get("generic") and c["sub"] != "drone" and c["sub"] != sub["id"]:
        return False, 999.0

    if pos and pos[0] not in LAUNCH_ONLY_ORIGINS and not pos[0].startswith("підліт"):
        p_dist = hav(pos[1], pos[2], c["lat"], c["lon"])
        g_dist = hav(pos[1], pos[2], c["goal"][1], c["goal"][2]) if c.get("goal") else p_dist
        eff_d = min(p_dist, g_dist)
        max_fuse_km = 8.0 if sub["id"] in TACTICAL_SHORT_DRONES else 15.0
        if eff_d <= max_fuse_km:
            return True, eff_d / (max_fuse_km + 5.0)
        return False, 999.0

    if tgt and not pos:
        d_to_tgt = hav(c["lat"], c["lon"], tgt[1], tgt[2])
        d_goal_tgt = hav(c["goal"][1], c["goal"][2], tgt[1], tgt[2]) if c.get("goal") else d_to_tgt
        eff_d = min(d_to_tgt, d_goal_tgt)
        if sub["id"] in TACTICAL_SHORT_DRONES:
            max_tgt_km = 8.5
        elif is_turn or tgt[0] in ZP_DISTRICTS or (c.get("holding") and not c.get("passed_goal")):
            max_tgt_km = 45.0
        else:
            max_tgt_km = 15.0
        if eff_d <= max_tgt_km:
            b_to_tgt = brg(c["lat"], c["lon"], tgt[1], tgt[2])
            if (120.0 <= b_to_tgt <= 235.0) and not is_turn and not c.get("holding") and tgt[0] not in ZP_DISTRICTS and d_to_tgt > 5.0:
                return False, 999.0
            bonus = -0.25 if (is_turn or c.get("passed_goal") or c.get("holding") or c.get("provisional_goal")) else 0.0
            return True, max(0.01, (eff_d / (max_tgt_km + 5.0)) + bonus)
        return False, 999.0

    if (is_turn or hdg_ovr is not None) and not pos:
        return True, 0.1

    return False, 999.0

def upsert(sub, pos, tgt, ts, text, ch="канал", cnt=None, v_ovr=None, hdg_ovr=None, from_brg=None, is_turn=False, is_loiter=False, force_new=False, msg_key=None, manual=False, is_explicit_over=False, is_arrived=False):
    now = time.time()
    te = min(ts + REPORT_LAG, now)

    pos, tgt, hdg_ovr, is_provisional = sanitize_tactical_route(sub["kind"], pos, tgt, hdg_ovr=hdg_ovr, manual=manual)

    if sub["kind"] == "drone":
        ref_pt = tgt or pos
        for k_id, kt in list(tracks.items()):
            if kt["kind"] == "kab" and not kt.get("ended") and kt.get("provisional_goal") and (now - kt.get("seen", 0) < 120):
                if not ref_pt or hav(kt["lat"], kt["lon"], ref_pt[1], ref_pt[2]) <= 18.0 or (kt.get("goal") and hav(kt["goal"][1], kt["goal"][2], ref_pt[1], ref_pt[2]) <= 18.0):
                    tracks.pop(k_id, None)

    live = [
        t for t in tracks.values()
        if t["kind"] == sub["kind"]
        and (not t.get("ended") or (t.get("auto_ended") and now - t.get("ended_at", 0) < 45))
        and now - t["seen"] < t["ttl"]
    ]
    for c in live:
        if not c.get("ended"):
            step(c, now)

    best_t, best_cost = None, 1.0
    for c in live:
        ok, cost = can_fuse_into_track(c, sub, pos, tgt, hdg_ovr, te, is_turn=is_turn, force_new=force_new)
        if ok and cost < best_cost:
            best_cost, best_t = cost, c

    if best_t is None:
        explicit_origin = bool(pos)
        if not pos and tgt:
            if sub["kind"] == "kab":
                pos = real_kab_launch_origin_for(tgt)
            elif sub["kind"] == "drone":
                pos = realistic_drone_approach_origin(sub["id"], tgt, hdg_ovr=hdg_ovr, from_brg=from_brg, is_arrived=is_arrived)
            else:
                pos = tgt
                tgt = None
        if not pos:
            return None

        eff_goal = adjust_city_entry_goal(pos, tgt) if (sub["kind"] == "drone" and tgt and not is_arrived) else tgt

        i = next(ids)
        v = v_ovr or sub["v"]
        init_hdg = None
        holding = False
        proj_km = 2.2 if sub["id"] in TACTICAL_SHORT_DRONES else (5.5 if v < 400 else 18.0)

        if eff_goal and hav(pos[1], pos[2], eff_goal[1], eff_goal[2]) >= 0.15:
            init_hdg = brg(pos[1], pos[2], eff_goal[1], eff_goal[2])
        elif hdg_ovr is not None:
            init_hdg = hdg_ovr
            gla, glo = fwd(pos[1], pos[2], init_hdg, proj_km)
            eff_goal = (f"курс {round(init_hdg)}°", gla, glo)
        elif from_brg is not None:
            init_hdg = (from_brg + 180.0) % 360
            gla, glo = fwd(pos[1], pos[2], init_hdg, proj_km)
            eff_goal = (pos[0], gla, glo)
        else:
            holding = True
            eff_goal = None
            init_hdg = None

        sg = sigma_of(pos[0])
        status_msg = f"Кружляє ({pos[0]})" if is_loiter else (f"Очікує курс ({pos[0]})" if holding else None)
        t = tracks[i] = dict(
            id=i, kind=sub["kind"], sub=sub["id"], ttl=sub["ttl"], v=v,
            o=(pos[1], pos[2]), frm=pos[0], to_name=tgt[0] if tgt else (eff_goal[0] if eff_goal else pos[0]),
            explicit_origin=explicit_origin, provisional_goal=bool(is_provisional),
            lat=pos[1], lon=pos[2], hdg=init_hdg, thdg=init_hdg,
            loiter=bool(is_loiter), holding=bool(holding or is_loiter), anchor=(pos[1], pos[2]), orb_ang=0.0, manual=bool(manual),
            unc=sg, goal=eff_goal, passed_goal=False, ls=now, seen=(now if manual else min(now, ts)), last_msg_ts=ts, fix_seq=1, n=1,
            fx=[(te, pos[1], pos[2], sg)], text=text, cnt=cnt,
            status_msg=status_msg,
            channels={ch} if ch else set(),
            msg_keys={msg_key} if msg_key else set(),
            obs={}
        )
        t["obs"][ch or f"c{i}"] = dict(ts=te, lat=pos[1], lon=pos[2], goal=eff_goal, hdg=init_hdg, v=v, explicit=explicit_origin)
        if not manual and 10 < now - ts <= 900 and t.get("hdg") is not None and not t.get("holding"):
            cur = ts                       # повідомлення старе — дорахувати, де ціль мала б бути зараз
            t["ls"] = ts
            while cur < now:
                cur = min(now, cur + 30.0)
                step(t, cur)
        return t

    t = best_t
    if ch:
        t["channels"].add(ch)
    if msg_key:
        t["msg_keys"].add(msg_key)
    t["n"] = max(t["n"] + 1, len(t["channels"]))

    if not manual and ts < t.get("last_msg_ts", 0) - 45:
        return t
    t["last_msg_ts"] = max(t.get("last_msg_ts", 0), ts)

    if t.get("ended"):
        t["ended"] = False
        t["auto_ended"] = False
        t["ls"] = now
    if not sub.get("generic"):
        t["sub"] = sub["id"]
        t["ttl"] = sub["ttl"]
        t["v"] = v_ovr or sub["v"]
    elif v_ovr:
        t["v"] = v_ovr
    elif not t["v"]:
        t["v"] = sub["v"]

    t["seen"] = max(t.get("seen", 0), now if manual else min(now, ts))
    t["fix_seq"] = t.get("fix_seq", 1) + 1
    look_km = default_lookahead_km(t)

    if t["kind"] == "kab":
        if pos and not pos[0].startswith("підліт") and pos[0] not in LAUNCH_ONLY_ORIGINS and pos[0] != t["frm"]:
            t["frm"] = pos[0]
            t["lat"], t["lon"] = pos[1], pos[2]
            t["o"] = (pos[1], pos[2])
        if tgt:
            t["provisional_goal"] = False
            t["goal"] = tgt
            t["to_name"] = tgt[0]
            t["passed_goal"] = False
            t["holding"] = False
            t["ls"] = now
            if hav(t["lat"], t["lon"], tgt[1], tgt[2]) > 0.25:
                new_b = brg(t["lat"], t["lon"], tgt[1], tgt[2])
                t["hdg"] = t["thdg"] = new_b
                t["status_msg"] = None
        elif hdg_ovr is not None:
            t["provisional_goal"] = False
            gla, glo = fwd(t["lat"], t["lon"], hdg_ovr, 26.0)
            t["goal"] = (f"курс {round(hdg_ovr)}°", gla, glo)
            t["to_name"] = f"курс {round(hdg_ovr)}°"
            t["passed_goal"] = False
            t["holding"] = False
            t["ls"] = now
            t["hdg"] = t["thdg"] = hdg_ovr
            t["status_msg"] = None
    else:
        prev_lat, prev_lon = t["lat"], t["lon"]
        prev_goal = t.get("goal")
        prev_hdg = t.get("hdg")
        prev_to = t.get("to_name")
        was_holding = bool(t.get("holding") or t.get("loiter"))

        if pos and not pos[0].startswith("підліт") and pos[0] not in LAUNCH_ONLY_ORIGINS:
            same_place_repeat = (pos[0] == t["frm"] and not manual and hav(t["lat"], t["lon"], pos[1], pos[2]) <= 4.0)
            t["frm"] = pos[0]
            if not same_place_repeat:
                t["lat"], t["lon"] = pos[1], pos[2]
                t["ls"] = now
            t["obs"][ch or f"u{t['n']}"] = dict(ts=te, lat=pos[1], lon=pos[2], goal=tgt, hdg=hdg_ovr, v=t["v"], explicit=True)

        if is_loiter:
            t["loiter"] = True
            t["holding"] = True
            t["goal"] = None
            t["passed_goal"] = False
            clean_p = pos[0] if pos else t["frm"]
            t["status_msg"] = f"Кружляє ({clean_p})"
        elif tgt:
            t["loiter"] = False
            t["holding"] = False
            t["provisional_goal"] = False
            t["ls"] = now
            if not pos:
                if prev_goal and prev_to and prev_to != tgt[0] and not str(prev_to).startswith("курс"):
                    d_old_to_new = hav(prev_goal[1], prev_goal[2], tgt[1], tgt[2])
                    d_cur_to_new = hav(t["lat"], t["lon"], tgt[1], tgt[2])
                    if d_old_to_new < d_cur_to_new and d_old_to_new <= 10.0:
                        t["lat"], t["lon"] = prev_goal[1], prev_goal[2]
                        t["frm"] = prev_to
                        t["ls"] = now
                elif str(t["frm"]).startswith("підліт"):
                    d_rem = hav(t["lat"], t["lon"], tgt[1], tgt[2])
                    if d_rem > 6.5:
                        in_b = brg(tgt[1], tgt[2], t["lat"], t["lon"])
                        app_km = 2.0 if t["sub"] in TACTICAL_SHORT_DRONES else (3.6 if tgt[0] in ZP_DISTRICTS else 4.8)
