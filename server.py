def parse_iso_ts(dt_str):
    if not dt_str:
        return time.time()
    try:
        s = str(dt_str).strip()
        if s.endswith("Z"):
            s = s[:-1] + "+00:00"
        return datetime.fromisoformat(s).timestamp()
    except Exception:
        return time.time()

def clean_post(raw_text):
    if not raw_text:
        return ""
    lines = []
    for ln in raw_text.replace("\r", "\n").split("\n"):
        s = ln.strip()
        if not s:
            continue
        if FOOTER_ONLY_LINE_RX.match(s):
            continue
        s = re.sub(r"https?://\S+|t\.me/\S+|@\w+", "", s).strip()
        s = INLINE_SIGNATURE_STRIP_RX.sub("", s).strip(" -–—•|")
        s = SAFETY_REMINDER_STRIP_RX.sub("", s).strip(" -–—•|,")
        s_no_hdr = REGION_HEADER_RX.sub("", s).strip(" -–—•|,")
        if s_no_hdr:
            s = s_no_hdr
        if s:
            lines.append(s)
    return "\n".join(lines).strip()

