async def send(payload, event=None):
    msg = (f"event: {event}\n" if event else "") + f"data: {json.dumps(payload, ensure_ascii=False)}\n\n"
    for c in list(clients):
        try:
            await c.write(msg.encode())
        except Exception:
            clients.discard(c)

