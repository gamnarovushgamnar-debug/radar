async def probe_next_embed(s, ch, next_id, headers):
    try:
        url = f"https://t.me/{ch}/{next_id}?embed=1&mode=tme"
        async with s.get(url, headers=headers, timeout=aiohttp.ClientTimeout(total=2.5)) as r:
            if r.status != 200:
                return None
            html = await r.text()
        if "tgme_widget_message_text" not in html:
            return None
        w = BeautifulSoup(html, "html.parser").select_one(".tgme_widget_message")
        if not w:
            return None
        pid = w.get("data-post") or f"{ch}/{next_id}"
        tm = w.select_one("time")
        main_text, reply_ctx = extract_tg_message_and_reply(w)
        if not main_text:
            return None
        ts = parse_iso_ts(tm.get("datetime")) if tm else time.time()
        return (ts, main_text, pid, reply_ctx, next_id)
    except Exception:
        return None

