def effective_speed(t):
    v = t["v"]
    if not v or t.get("ended") or t.get("hdg") is None:
        return 0
    if t["kind"] == "kab":
        flown = hav(*t["o"], t["lat"], t["lon"])
        factor = max(0.72, 1.0 - 0.30 * (flown / KAB_RANGE))
        if t.get("passed_goal"):
            factor = min(factor, 0.68)
        return round(v * factor)
    if t["kind"] == "drone" and t.get("passed_goal"):
        return round(v * 0.65)
    return v

def step(t, now):
    """Рухає ціль за вектором з розумною логікою поведінки над містом."""
    dt = min(now - t["ls"], 1800.0)
    if dt <= 0:
        return
    t["ls"] = now
    if t.get("ended"):
        return
    v_eff = effective_speed(t)
    if not v_eff or t["hdg"] is None:
        return

    if t.get("thdg") is not None and t["hdg"] is not None:
        diff = ang(t["thdg"] - t["hdg"])
        if abs(diff) > 0.5:
            turn_rate = 22.0 if t["kind"] == "kab" else 30.0
            max_turn = turn_rate * dt
            t["hdg"] = (t["hdg"] + max(-max_turn, min(max_turn, diff))) % 360

    g = t["goal"]
    step_km = v_eff * dt / 3600.0
    if g and not t.get("passed_goal"):
        rem_g = hav(t["lat"], t["lon"], g[1], g[2])
        if rem_g > 0.45 and step_km < rem_g:
            t["thdg"] = brg(t["lat"], t["lon"], g[1], g[2])
            if abs(ang(t["thdg"] - t["hdg"])) < 18.0:
                t["hdg"] = t["thdg"]
            t["lat"], t["lon"] = fwd(t["lat"], t["lon"], t["hdg"], step_km)
        else:
            # Ціль досягла вказаного орієнтира g[0]!
            t["lat"], t["lon"] = g[1], g[2]
            t["frm"] = g[0]
            t["passed_goal"] = True
            t["passed_at"] = now

            # ВИПРАВЛЕННЯ v8:
            # Якщо БпЛА долетів до м. Запоріжжя або конкретного мікрорайону Запоріжжя,
            # він НЕ вигадує подальший курс по прямій через усе місто, а переходить у статус
            # «Над <район/місто> (очікує уточнення курсу)», готовий миттєво повернути за командою («курс Зелений», «на Шевчик» тощо)!
            if t["kind"] == "drone" and (g[0] == "Запоріжжя" or g[0] in ZP_DISTRICTS):
                t["hdg"] = None
                t["thdg"] = None
                t["goal"] = None
                t["to_name"] = None
                clean_g = g[0].replace(" (ЗП)", "")
                t["status_msg"] = f"Над {clean_g} · маневрує / очікує курс"
            else:
                cont_km = 14.0 if t["kind"] == "kab" else (10.0 if t["kind"] == "drone" else 22.0)
                gla, glo = fwd(t["lat"], t["lon"], t["hdg"], cont_km)
                t["goal"] = (f"далі за курсом від {g[0]}", gla, glo)
                t["status_msg"] = f"Пройшов {g[0]} · у повітрі (курс {round(t['hdg'])}°)"
    else:
        t["lat"], t["lon"] = fwd(t["lat"], t["lon"], t["hdg"], step_km)
        if t.get("passed_goal") and g:
            if hav(t["lat"], t["lon"], g[1], g[2]) <= 1.0:
                gla, glo = fwd(t["lat"], t["lon"], t["hdg"], 10.0)
                t["goal"] = (t["goal"][0], gla, glo)

    if t["kind"] == "kab":
        if hav(*t["o"], t["lat"], t["lon"]) >= KAB_RANGE or (t.get("passed_goal") and now - t.get("passed_at", now) > 110 and now - t["seen"] > 90):
            t["ended"] = True
            t["auto_ended"] = True
            t["status_msg"] = "⏳ Локаційно не фіксується (ймовірно впав)"
            t["ended_at"] = now

    umax = 4.5 if v_eff < 400 else 8.0
    t["unc"] = min(umax, t["unc"] + dt * v_eff / 3600 * 0.035)

