def resolve_tracks_status(kinds, loc, status_label, one=False):
    now = time.time()
    cand = [
        t for t in tracks.values()
        if not t.get("ended")
        and (not kinds or t["kind"] in kinds)
        and (
            not loc
            or hav(t["lat"], t["lon"], loc[1], loc[2]) < 45
            or (t["goal"] and hav(t["goal"][1], t["goal"][2], loc[1], loc[2]) < 25)
        )
    ]
    if not cand and not kinds and loc:
        cand = [
            t for t in tracks.values()
            if not t.get("ended") and (
                hav(t["lat"], t["lon"], loc[1], loc[2]) < 35
                or (t["goal"] and hav(t["goal"][1], t["goal"][2], loc[1], loc[2]) < 20)
            )
        ]
    if not cand and not loc and not kinds:
        kabs = [t for t in tracks.values() if t["kind"] == "kab" and not t.get("ended")]
        cand = kabs if kabs else ([max(tracks.values(), key=lambda x: x["seen"])] if tracks else [])

    if one and loc and cand:
        cand = [min(cand, key=lambda t: hav(t["lat"], t["lon"], loc[1], loc[2]))]

    for t in cand:
        t["ended"] = True
        t["auto_ended"] = False
        t["ended_at"] = now
        t["v"] = 0
        t["status_msg"] = status_label
        if loc and loc[0] not in BROAD_REGIONS:
            t["lat"], t["lon"] = loc[1], loc[2]
        t["seen"] = now
        if t.get("to_name"):
            ended_cooldown[(t["kind"], t["to_name"])] = now
        if t.get("frm"):
            ended_cooldown[(t["kind"], t["frm"])] = now

def infer_implicit_subs(tl, pos, tgt, ch):
    if not IMPLICIT_FLIGHT_RX.search(tl):
        return []
    m_cnt = ANY_CNT_RX.search(tl)
    cnt = m_cnt.group(1) if m_cnt else None
    if IMPLICIT_KAB_RX.search(tl):
        return [(SUB["kab"], cnt)]
    ref = pos or tgt
    now = time.time()
    live = [t for t in tracks.values() if t["kind"] not in ("strike", "impact") and not t.get("ended") and now - t["seen"] < t["ttl"]]
    if ref and live:
        near = min(live, key=lambda t: hav(t["lat"], t["lon"], ref[1], ref[2]))
        if hav(near["lat"], near["lon"], ref[1], ref[2]) <= 38.0:
            return [(SUB[near["sub"]], cnt)]
    if ch in ch_last_sub and now - ch_last_sub[ch][0] <= 480:
        return [(ch_last_sub[ch][1], cnt)]
    return [(SUB["geran2"], cnt)]

def act(intent, subs, pos, tgt, ts, text, ch, how="", v_ovr=None, hdg_ovr=None, is_turn=False, msg_key=None, ai_flag=False):
    loc = pos or tgt
    kinds = list(dict.fromkeys(sb["kind"] for sb, _ in subs if sb["kind"] not in ("strike", "impact")))
    tag = f"{ch}{how}: «{text[:55]}» → "

    if intent == "downed":
        resolve_tracks_status(kinds, loc, "🛡 Збито / Локаційно втрачено", one=bool(loc))
        feed_add(ts, ch, text, kinds or ["drone"], pos, tgt)
        return note(tag + "ЗБИТО / ЛОКАЦІЙНО ВТРАЧЕНО")

    if intent == "clear":
        resolve_tracks_status(kinds, loc, "🟢 Відбій / Чисто", one=False)
        feed_add(ts, ch, text, kinds or ["drone"], pos, tgt)
        return note(tag + "ВІДБІЙ / ЧИСТО")

    if intent == "impact":
        resolve_tracks_status(kinds, loc, "💥 Впав / Приліт", one=False)
        if loc and loc[0] not in BROAD_REGIONS:
            names = list(dict.fromkeys(sb["name"] for sb, _ in subs if sb["kind"] not in ("strike", "impact")))
            m = upsert(SUB["impact"], loc, None, ts, text, ch=ch, cnt=next((c for _, c in subs if c), None))
            if m:
                m["label"] = ("💥 Приліт: " + ", ".join(names)) if names else "💥 Приліт/вибух"
        feed_add(ts, ch, text, ["impact"] + kinds, pos, tgt)
        return note(tag + f"ВПАВ / ПРИЛІТ ({loc and loc[0] or 'по активних цілях'})")

    if not subs:
        subs = infer_implicit_subs(text.lower(), pos, tgt, ch)
        if not subs:
            return note(tag + "немає типу цілі та ознак польоту, пропуск")

    for sb, cnt in subs:
        ch_last_sub[ch] = (time.time(), sb)
        if sb["kind"] == "strike":
            if loc and loc[0] not in BROAD_REGIONS:
                upsert(sb, loc, None, ts, text, ch=ch, cnt=cnt, msg_key=msg_key, ai_flag=ai_flag)
        else:
            upsert(sb, pos, tgt, ts, text, ch=ch, cnt=cnt, v_ovr=v_ovr, hdg_ovr=hdg_ovr, is_turn=is_turn, msg_key=msg_key, ai_flag=ai_flag)
    feed_add(ts, ch, text, [sb["kind"] for sb, _ in subs], pos, tgt)
    note(tag + f"{[(sb['id'], c) for sb, c in subs]} поз={pos and pos[0]} ціль={tgt and tgt[0]} курс={hdg_ovr}")

def ingest_segment(ts, seg, ch="", msg_key=None, inherited_subs=None, reply_ctx=None, full_post_has_zp=False):
    tl = seg.lower()
    has_zp = bool(ZP_UNIQUE_RX.search(tl)) or full_post_has_zp or bool(reply_ctx and ZP_UNIQUE_RX.search(reply_ctx.get("text", "").lower()))

    if OTHER_OBLAST_RX.search(tl) and not ZP_UNIQUE_RX.search(tl):
        return []

    if ch.lower() in ALL_UA_CHANNELS and not has_zp:
        return []

    if PURE_ALARM_RX.match(tl):
        feed_add(ts, ch, seg, ["kab"], None, None)
        return []

    intent = intent_of(tl)
    subs = detect(tl) or inherited_subs or (reply_ctx.get("subs") if reply_ctx else None) or []
    v_ovr, hdg_ovr = parse_speed_hdg(tl)
    is_turn = bool(TURN_RX.search(tl))
    routes = extract_routes(tl)

    if not has_zp and ch.lower() in ALL_UA_CHANNELS and routes:
        routes = [
            (p, g) for (p, g) in routes
            if not ((p and p[0] in AMBIGUOUS_PLACES) or (g and g[0] in AMBIGUOUS_PLACES))
        ]

    if not routes and reply_ctx and reply_ctx.get("routes"):
        if intent in ("clear", "downed", "impact"):
            r0 = reply_ctx["routes"][0]
            loc = r0[1] or r0[0]
            routes = [(loc, None)] if loc else []
        elif is_turn or hdg_ovr is not None:
            r0 = reply_ctx["routes"][0]
            routes = [(r0[1] or r0[0], None)]

    if intent in ("clear", "downed", "impact") and not routes:
        if has_zp or ch.lower() not in ALL_UA_CHANNELS:
            act(intent, subs, None, None, ts, seg, ch, msg_key=msg_key)
        return subs

    if not routes:
        if (is_turn or hdg_ovr is not None) and tracks and (has_zp or ch.lower() not in ALL_UA_CHANNELS):
            live = [t for t in tracks.values() if t["kind"] not in ("strike", "impact") and not t.get("ended")]
            if live:
                latest = max(live, key=lambda c: c["seen"])
                proj_km = 22.0 if latest["v"] < 400 else 50.0
                gla, glo = fwd(latest["lat"], latest["lon"], hdg_ovr or 330, proj_km)
                latest["goal"] = (f"курс {round(hdg_ovr or 330)}°", gla, glo)
                latest["passed_goal"] = False
                latest["hdg"] = latest["thdg"] = hdg_ovr or 330
                latest["status_msg"] = f"↪ Змінив курс ({round(hdg_ovr or 330)}°)"
                return subs
        return subs

    if intent == "impact" and not [1 for sb, _ in subs if sb["kind"] != "strike"]:
        subs = [x for x in subs if x[0]["id"] != "arty"]

    for r_idx, (pos, tgt) in enumerate(routes):
        r_key = f"{msg_key}:r{r_idx}" if msg_key else None
        act(intent, subs, pos, tgt, ts, seg, ch, v_ovr=v_ovr, hdg_ovr=hdg_ovr, is_turn=is_turn, msg_key=r_key)
    return subs

def ingest(ts, text, ch="", msg_key=None, reply_ctx=None):
    now = time.time()
    for t in tracks.values():
        step(t, now)
    cleaned = clean_post(text)
    if not cleaned or REAL_NEWS_RX.search(cleaned.lower()) or len(cleaned) > 650:
        return note(f"{ch}: «{text[:50]}» → новина/не зведення, пропуск")
    full_has_zp = bool(ZP_UNIQUE_RX.search(cleaned.lower()))
    lines = [ln.strip(" •▪▫-*—–") for ln in cleaned.split("\n") if len(ln.strip()) >= 3]
    if len(lines) > 1:
        inherited = detect(lines[0].lower()) if not OTHER_OBLAST_RX.search(lines[0].lower()) else []
        for idx, ln in enumerate(lines):
            sub_key = f"{msg_key}:{idx}" if msg_key else None
            cur_subs = ingest_segment(ts, ln, ch, msg_key=sub_key, inherited_subs=inherited, reply_ctx=reply_ctx, full_post_has_zp=full_has_zp)
            if cur_subs:
                inherited = cur_subs
    else:
        ingest_segment(ts, cleaned, ch, msg_key=msg_key, reply_ctx=reply_ctx, full_post_has_zp=full_has_zp)

