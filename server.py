async def tick(s):
    while True:
        now = time.time()
        for i, t in list(tracks.items()):
            if t.get("ended"):
                if now - t.get("ended_at", t["seen"]) > 45:
                    tracks.pop(i, None)
            elif now - t["seen"] > t["ttl"]:
                t["ended"] = True
                t["auto_ended"] = True
                t["ended_at"] = now - 15
                t["v"] = 0
                t["status_msg"] = "⏳ Локаційно втрачено"
        for t in list(tracks.values()):
            step(t, now)
            if t["kind"] != "kab" or t.get("ended") or not t["goal"] or hav(*t["goal"][1:], HOME[1], HOME[2]) > 25:
                continue
            v = view(t, now)
            if v["short"]:
                continue
            lvl = 2 if v["eta"] is not None and v["eta"] <= ALERT_ETA2 else 1
            if (t["id"], lvl) not in alerted:
                alerted.add((t["id"], lvl))
                txt = f"КАБ на {HOME[0]}! Пуск: {t['frm']}, {v['home']} км, висота {v.get('alt')} м, ~{v['eta']} с"
                await send({"lvl": lvl, "text": txt}, "alert")
                if NTFY:
                    try:
                        await s.post(
                            f"https://ntfy.sh/{NTFY}",
                            data=txt.encode(),
                            headers={"Title": "KAB ALERT", "Priority": "urgent", "Tags": "rotating_light"}
                        )
                    except Exception as e:
                        print("ntfy", e)
        await push()
        await asyncio.sleep(1)

def extract_tg_message_and_reply(w):
    reply_ctx = None
    reply_a = w.select_one(".tgme_widget_message_reply")
    if reply_a:
        r_pid = reply_a.get("href", "").split("/")[-1]
        r_tx_el = reply_a.select_one(".tgme_widget_message_text")
        r_tx = r_tx_el.get_text(" ", strip=True) if r_tx_el else ""
        if r_pid and any(k.endswith("/" + r_pid) for k in post_memory):
            for k, v in post_memory.items():
                if k.endswith("/" + r_pid):
                    reply_ctx = v
                    break
        elif r_tx:
            rc = clean_post(r_tx).lower()
            reply_ctx = {"subs": detect(rc), "routes": extract_routes(rc), "text": r_tx}
        reply_a.decompose()

    tx_el = w.select_one(".js-message_text") or w.select_one(".tgme_widget_message_text")
    if not tx_el:
        return None, None
    for br in tx_el.find_all("br"):
        br.replace_with("\n")
    main_text = tx_el.get_text(" ", strip=True)
    return main_text, reply_ctx

async def probe_next_embed(s, ch, next_id, headers):
    try:
        url = f"https://t.me/{ch}/{next_id}?embed=1&mode=tme"
        async with s.get(url, headers=headers, timeout=aiohttp.ClientTimeout(total=2.5)) as r:
            if r.status != 200:
                return None
            html = await r.text()
        if "tgme_widget_message_text" not in html:
            return None
        w = BeautifulSoup(html, "html.parser").select_one(".tgme_widget_message")
        if not w:
            return None
        pid = w.get("data-post") or f"{ch}/{next_id}"
        tm = w.select_one("time")
        main_text, reply_ctx = extract_tg_message_and_reply(w)
        if not main_text:
            return None
        ts = datetime.fromisoformat(tm["datetime"]).timestamp() if (tm and tm.get("datetime")) else time.time()
        return (ts, main_text, pid, reply_ctx, next_id)
    except Exception:
        return None

async def poll(s, ch):
    first = True
    cycle = 0
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/125.0.0.0 Safari/537.36",
        "Accept-Language": "uk-UA,uk;q=0.9,en-US;q=0.8",
        "Cache-Control": "no-cache, no-store, must-revalidate",
        "Pragma": "no-cache"
    }
    while True:
        try:
            new = []
            if not first and ch in last_ch_id:
                nxt = last_ch_id[ch] + 1
                res = await probe_next_embed(s, ch, nxt, headers)
                if res:
                    ts, main_text, pid, reply_ctx, num_id = res
                    last_ch_id[ch] = max(last_ch_id.get(ch, 0), num_id)
                    if seen_text.get(pid) != main_text:
                        seen_text[pid] = main_text
                        cl = clean_post(main_text).lower()
                        post_memory[pid] = {"subs": detect(cl), "routes": extract_routes(cl), "text": main_text}
                        new.append((ts, main_text, pid, reply_ctx))

            if first or cycle % 2 == 0 or not new:
                url = f"https://t.me/s/{ch}?_={int(time.time() * 1000)}"
                async with s.get(url, headers=headers, timeout=aiohttp.ClientTimeout(total=4.5)) as r:
                    html, code = await r.text(), r.status
                ws = BeautifulSoup(html, "html.parser").select(".tgme_widget_message")
                stats[ch] = {
                    "http": code, "html_len": len(html), "messages_on_page": len(ws),
                    "checked": time.strftime("%H:%M:%S")
                }
                for w in ws[-15:]:
                    pid, tm = w.get("data-post"), w.select_one("time")
                    if not (pid and tm):
                        continue
                    try:
                        num_id = int(pid.split("/")[-1])
                        last_ch_id[ch] = max(last_ch_id.get(ch, 0), num_id)
                    except Exception:
                        pass
                    main_text, reply_ctx = extract_tg_message_and_reply(w)
                    if not main_text:
                        continue
                    stats[ch]["last_post"] = main_text[:200]
                    if seen_text.get(pid) == main_text:
                        continue
                    is_edit = pid in seen_text
                    seen_text[pid] = main_text
                    if len(seen_text) > 1200:
                        seen_text.pop(next(iter(seen_text)))
                    ts = datetime.fromisoformat(tm["datetime"]).timestamp()
                    if is_edit:
                        ts = time.time()
                    cl = clean_post(main_text).lower()
                    post_memory[pid] = {"subs": detect(cl), "routes": extract_routes(cl), "text": main_text}
                    if len(post_memory) > 500:
                        post_memory.pop(next(iter(post_memory)))
                    if not first or time.time() - ts < INITIAL_LOOKBACK:
                        new.append((ts, main_text, pid, reply_ctx))
                first = False

            cycle += 1
            for ts, text, pid, reply_ctx in sorted(new, key=lambda x: x[0]):
                await process(s, ts, text, ch, msg_key=pid, reply_ctx=reply_ctx)
        except Exception as e:
            stats[ch] = {"error": str(e), "checked": time.strftime("%H:%M:%S")}
        await asyncio.sleep(POLL)

async def sim_endpoint(req):
    try:
        data = await req.json()
        if data.get("clear"):
            tracks.clear()
            ended_cooldown.clear()
            await push()
            return web.json_response({"ok": True, "tracks": 0})
        if data.get("dismiss") is not None:
            tid = int(data["dismiss"])
            t = tracks.pop(tid, None)
            if t and t.get("to_name"):
                ended_cooldown[(t["kind"], t["to_name"])] = time.time()
            await push()
            return web.json_response({"ok": True, "tracks": len(tracks)})
        # Пряме керування ціллю з інтерфейсу (розворот на будь-який район або точку на карті!)
        if data.get("steer") is not None:
            st = data["steer"]
            tid = int(st.get("id", 0))
            t = tracks.get(tid)
            if t:
                now = time.time()
                step(t, now)
                if st.get("loiter"):
                    t["goal"] = None
                    t["to_name"] = None
                    t["hdg"] = None
                    t["thdg"] = None
                    t["status_msg"] = f"Кружляє в районі {t['frm'].replace(' (ЗП)', '')}"
                elif st.get("lat") is not None and st.get("lon") is not None:
                    tla, tlo = float(st["lat"]), float(st["lon"])
                    tname = str(st.get("name") or "Вказана точка")
                    t["goal"] = (tname, tla, tlo)
                    t["to_name"] = tname
                    t["passed_goal"] = False
                    new_b = brg(t["lat"], t["lon"], tla, tlo)
                    t["thdg"] = t["hdg"] = new_b
                    t["status_msg"] = f"↪ Курс на {tname.replace(' (ЗП)', '')}"
                t["seen"] = now
                await push()
                return web.json_response({"ok": True, "tracks": len(tracks)})
        if data.get("add_channel"):
            ch_new = re.sub(r"^.*t\.me/(?:s/)?|@", "", str(data["add_channel"]).strip()).strip("/")
            if re.match(r"^[a-zA-Z0-9_]{4,40}$", ch_new) and ch_new not in CHANNELS:
                CHANNELS.append(ch_new)
                asyncio.create_task(poll(req.app["session"], ch_new))
                await push()
            return web.json_response({"ok": True, "channels": CHANNELS})
        text = str(data.get("text", "")).strip()
        ch = str(data.get("ch", "оператор")).strip() or "оператор"
        if not text:
            return web.json_response({"ok": False, "error": "empty text"}, status=400)
        ts = time.time()
        await process(req.app["session"], ts, text, ch, msg_key=f"sim/{int(ts*1000)}")
        return web.json_response({"ok": True, "tracks": len(tracks)})
    except Exception as e:
        return web.json_response({"ok": False, "error": str(e)}, status=500)

